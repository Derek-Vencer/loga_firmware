	//Address 0x00 bits[7:2] 		/ 0x01 bits[3:0] 	/ 0x02 					=> Red	 D1~D10
	//Address 0x00					/ 0x01 bits[7:6] 	/ 0x02 bits[7:0]		=> Green D1~D10
	//Address 0x03 bits[7:2] 		/ 0x04 bits[3:0] 	/ 0x05			 		=> Blue	 D1~D10
	//---------------------------------------------------------------------
	//Address 0x03					/ 0x04 bits[6:4] 	/ 0x05 bits[7:1]		=> Red	 D11~D20
	//Address 0x06 bits[7:5][2:0] 	/ 0x07 bits[3:0] 	/ 0x08			 		=> Green D11~D20
	//Address 0x06					/ 0x07 bits[6:4] 	/ 0x08 bits[6:0]		=> Blue	 D11~D20
	//----------------------------------------------------------------------
	//Address 0x09 bits[5:0] 		/ 0x0A bits[3:0] 	/ 0x0B				 	=> Red	 D21~D30
	//Address 0x09					/ 0x0A bits[7:4] 	/ 0x0B bits[7:4][1:0] 	=> Green D21~D30
	//Address 0x0C bits[5:0] 		/ 0x0D bits[4:0] 	/ 0x0E					=> Blue	 D21~D30
	//---------------------------------------------------------------------
	//Address 0x0C					/ 0x0D bits[7:4] 	/ 0x0E bits[7][4:0] 	=> Red	 D31~D40
	//Address 0x0F bits[7:0] 		/ 0x10 bits[3][0] 	/ 0x11					=> Green D31~D40
	//Address 0x0F					/ 0x10 bits[7:4] 	/ 0x11 bits[7][4:0] 	=> Blue	 D31~D40
	//---------------------------------------------------------------------
	//---------------------------------------------------------------------
	//LUT for Frame1Page : LED Control and Blink Control Ram 
	//Notice: This Table setting the R/G/B LEDs mapping value,
	//		  Setting start Address from 0x00 to 0x11 : LED Control Ram
	//		  Setting start Address from 0x12 to 0x23 : Blink Control Ram
	//----------------------------------------------------------------------

